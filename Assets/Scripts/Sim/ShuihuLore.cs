    public sealed class LoreEntry
    {
        public readonly string Topic;
        public readonly string Verse;
        public readonly string Note;
        public readonly string Question;
        public readonly string[] Options;
        public readonly int Answer;

        public LoreEntry(string topic, string verse, string note, string q, string a, string b, string c, int ans)
        {
            Topic = topic;
            Verse = verse;
            Note = note;
            Question = q;
            Options = new[] { a, b, c };
            Answer = ans;
        }
    }

