        /// <summary>梁山书场文化功名头衔（随通晓卷数晋升）。</summary>
        public static string ScholarTitle(int mastered)
        {
            if (mastered >= 72) return "水浒通儒";
            if (mastered >= 54) return "天机学究";
            if (mastered >= 36) return "白衣秀士";
            if (mastered >= 18) return "勾栏说书人";
            if (mastered >= 5) return "瓦舍听书客";
            return "初入书场";
        }

        public static string NextScholarHint(int mastered)
        {
            if (mastered >= 72) return "已登顶「水浒通儒」，通晓全部七十二卷讲古";
            int need = mastered < 5 ? 5 : mastered < 18 ? 18 : mastered < 36 ? 36 : mastered < 54 ? 54 : 72;
            return $"再通晓 {need - mastered} 卷晋升「{ScholarTitle(need)}」";
        }

